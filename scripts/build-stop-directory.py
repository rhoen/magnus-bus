#!/usr/bin/env python3
"""Refresh the local stop directory using SEPTA GTFS metadata and v2 releases.
Python standard library only. Usage: python3 scripts/build-stop-directory.py [--gtfs archive.zip]
"""
import argparse
import concurrent.futures
import csv
import datetime
import io
import json
from pathlib import Path
import urllib.parse
import urllib.request
import zipfile

SOURCE = 'https://www3.septa.org/developer/gtfs_public.zip'
API = 'https://www3.septa.org/api/v2/stops/?route_id='


def download(url):
    with urllib.request.urlopen(url, timeout=45) as response:
        return response.read()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--gtfs', type=Path)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'data/stop-directory.js')
    args = parser.parse_args()
    outer = zipfile.ZipFile(io.BytesIO(args.gtfs.read_bytes() if args.gtfs else download(SOURCE)))
    archive = zipfile.ZipFile(io.BytesIO(outer.read('google_bus.zip')))

    def rows(name):
        return list(csv.DictReader(io.StringIO(archive.read(name).decode('utf-8-sig'))))

    routes = [r for r in rows('routes.txt') if r['route_type'] in ('0', '3', '11')]
    directions = rows('directions.txt')

    def get_stops(route):
        records = json.loads(download(API + urllib.parse.quote(route['route_id'])))
        if not isinstance(records, list):
            raise ValueError('Invalid stop response for ' + route['route_id'])
        return route, records

    stops, stop_indices, output_routes, unavailable = [], {}, [], []
    # Retain every published release; the browser selects the latest effective
    # release per route. Never substitute next month's stops for today's stops.
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        for route, records in pool.map(get_stops, routes):
            route_id = route['route_id']
            if not records:
                unavailable.append(route_id)
                continue
            entry = {'id': route_id, 'kind': 'trolley' if route['route_type'] == '0' else 'bus',
                     'directions': {d['direction_id']: {'name': d['direction'], 'destination': d['direction_destination']}
                                    for d in directions if d['route_id'] == route_id}, 'releases': {}}
            for row in sorted(records, key=lambda r: (r['release_name'], int(r['direction_id']), int(r['stop_sequence']))):
                release, direction = row['release_name'], str(row['direction_id'])
                if direction not in entry['directions']:
                    raise ValueError('Missing direction metadata: ' + route_id)
                stop = [str(row['stop_id']), row['stop_name'], float(row['stop_lat']), float(row['stop_lon'])]
                key = tuple(stop)
                if key not in stop_indices:
                    stop_indices[key] = len(stops)
                    stops.append(stop)
                indices = entry['releases'].setdefault(release, {}).setdefault(direction, [])
                if stop_indices[key] not in indices:
                    indices.append(stop_indices[key])
            output_routes.append(entry)
    data = {'generated': datetime.datetime.now(datetime.timezone.utc).date().isoformat(),
            'source': SOURCE, 'metadataVersion': rows('feed_info.txt')[0]['feed_version'],
            'stops': stops, 'routes': output_routes, 'unavailableRoutes': unavailable}
    # Ordinary script also works for the existing file:// launch workflow.
    args.output.write_text('// Generated by scripts/build-stop-directory.py from public SEPTA data.\n'
                           'globalThis.MagnusBus.stopDirectory = ' + json.dumps(data, separators=(',', ':')) + ';\n')
    print('Routes without v2 stop data:', ', '.join(unavailable) or 'none')
    print(f'Wrote {len(stops)} stop records across {len(output_routes)} routes to {args.output}')


if __name__ == '__main__':
    main()
