import { readFile, mkdir, writeFile, copyFile } from 'node:fs/promises';
const files = ['tracking.js', 'page.js', 'worker.js'];
const source = (await Promise.all(files.map(f => readFile(new URL('../src/' + f, import.meta.url), 'utf8')))).map(s => s.replace(/^import .*from '\.\/.*';\n/gm, '')).join('\n');
await mkdir(new URL('../dist/server/', import.meta.url), { recursive: true });
await mkdir(new URL('../dist/.openai/', import.meta.url), { recursive: true });
await writeFile(new URL('../dist/server/index.js', import.meta.url), source);
await copyFile(new URL('../.openai/hosting.json', import.meta.url), new URL('../dist/.openai/hosting.json', import.meta.url));
const built = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
if (typeof built.default?.fetch !== 'function') throw new Error('Missing Worker fetch');
console.log('Built and validated dist/server/index.js');
